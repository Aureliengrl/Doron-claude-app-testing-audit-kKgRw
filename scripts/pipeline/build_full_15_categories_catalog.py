def get_category_for_subcat(subcat: str) -> str:
    for cat, subcats in SUBCATEGORIES_BY_CATEGORY.items():
        if subcat in subcats:
            return cat
    raise ValueError(f"Sous-catégorie inconnue : {subcat}")

def format_product_item(raw: dict, subcat: str) -> dict:
    cat = get_category_for_subcat(subcat)
    price = float(raw["price"])
    budget_tag = get_budget_tag(price)
    gender = raw.get("gender", "gender_mixte")
    
    tags = [
        gender,
        cat,
        subcat,
        budget_tag,
    ]
    for a in raw.get("ages", []):
        tags.append(a)
    for s in raw.get("styles", []):
        tags.append(s)
    for p in raw.get("persos", []):
        tags.append(p)
    for pa in raw.get("passions", []):
        tags.append(pa)
    for t in raw.get("types", []):
        tags.append(t)
    for o in raw.get("occasions", []):
        tags.append(o)
        
    pop = raw.get("popularity", 90)
    if pop >= 95:
        tags.append("popularite_5")
    elif pop >= 85:
        tags.append("popularite_4")
    else:
        tags.append("popularite_3")
        
    keywords = [
        raw["brand"].lower(),
        raw["name"].lower(),
        cat.replace("cat_", ""),
        subcat.replace("subcat_", "").replace("_", " "),
        "cadeau",
    ]
    words = re.findall(r"\w+", raw["name"].lower())
    for w in words:
        if len(w) > 2 and w not in keywords:
            keywords.append(w)
            
    return {
        "id": raw["id"],
        "name": raw["name"],
        "product_title": raw["name"],
        "title": raw["name"],
        "brand": raw["brand"],
        "price": price,
        "product_price": f"{price:.2f} €",
        "url": raw["url"],
        "product_url": raw["url"],
        "buyUrl": raw["url"],
        "image": raw["image"],
        "product_photo": raw["image"],
        "imageUrl": raw["image"],
        "description": raw["description"],
        "category": cat,
        "subcategory": subcat,
        "categories": [cat, subcat, raw["brand"].lower()],
        "subcategories": [subcat],
        "tags": list(dict.fromkeys(tags)),
        "keywords": list(dict.fromkeys(keywords)),
        "popularity": pop,
        "active": True,
        "source": "doron_universe_catalog",
    }

def main():
    # Vérification que TOUTES les sous-catégories des 15 catégories sont présentes
    all_subcats = [s for sublist in SUBCATEGORIES_BY_CATEGORY.values() for s in sublist]
    missing = set(all_subcats) - set(FULL_PRODUCTS_MAP.keys())
    if missing:
        raise ValueError(f"Sous-catégories non définies dans FULL_PRODUCTS_MAP : {missing}")
        
    catalog = []
    for subcat, prods in FULL_PRODUCTS_MAP.items():
        for p in prods:
            catalog.append(format_product_item(p, subcat))
            
    print("=" * 60)
    print(f"🎉 SUCCÈS : {len(catalog)} fiches produits générées !")
    print(f"✅ 15 Grandes catégories couvertes : {list(SUBCATEGORIES_BY_CATEGORY.keys())}")
    print(f"✅ {len(FULL_PRODUCTS_MAP)} Sous-catégories couvertes à 100%")
    print("=" * 60)
    
    FALLBACK_JSON.parent.mkdir(parents=True, exist_ok=True)
    with FALLBACK_JSON.open("w", encoding="utf-8") as f:
        json.dump(catalog, f, indent=2, ensure_ascii=False)
        
